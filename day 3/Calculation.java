class Addition
{
	public static void main (String args[])
	{
		int long_books = 5;
		int short_books = 7;
		int Result = long_books + short_books;
		System.out.println("total books are: "+ Result);
	}
}
class Subtrsction
{
	public static void main (String args[])
	{
		int long_books = 5;
		int short_books = 7;
		int Result = long_books - short_books;
		System.out.println("total books are: "+ Result);
	}
}